/* Correct the actual Sep 20 Qingguang doughnut visit to 14:30, preserving saved family reviews. */
(function(){
'use strict';
const days=window.TRIP_DATA||[];
const sep20=days.find(d=>d.date.startsWith('9/20'));
const sep21=days.find(d=>d.date.startsWith('9/21'));
if(!sep20||!sep21)return;
const shop='脆皮鮮奶甜甜圈 晴光總店';
const source=sep21.areas.find(a=>a.area==='晴光市場（ドーナツ）');
const donut=source?.places.find(p=>p.name===shop);
if(!donut)return;
source.places=source.places.filter(p=>p!==donut);
if(!source.places.length)sep21.areas=sep21.areas.filter(a=>a!==source);
const areaName='晴光市場（9/20 14:30 訪問済み）';
let target=sep20.areas.find(a=>a.area===areaName);
if(!target){
 target={area:areaName,area_query:'晴光市場 台北',places:[]};
 const nightMarket=sep20.areas.findIndex(a=>a.area==='寧夏夜市');
 sep20.areas.splice(nightMarket<0?sep20.areas.length:nightMarket,0,target);
}
if(!target.places.some(p=>p.name===shop))target.places.push({...donut,category:donut.category+'　✓ 9/20 14:30訪問済み'});
try{
 const key='taiwan-trip-reviews-v2';
 const all=JSON.parse(localStorage.getItem(key)||'{}');
 const newId=[sep20.date,areaName,shop].join('|');
 const oldIds=[
  [sep21.date,source.area,shop].join('|'),
  [sep20.date,'晴光市場（9/20 15:00 訪問済み）',shop].join('|')
 ];
 let changed=false;
 for(const oldId of oldIds){
  if(!all[oldId])continue;
  const old=all[oldId],current=all[newId]||{};
  all[newId]={...old,...current,visited:!!(old.visited||current.visited),ratings:{...(old.ratings||{}),...(current.ratings||{})},memo:current.memo||old.memo||''};
  delete all[oldId];changed=true;
 }
 // Only correct the former autogenerated visit-time memo; leave personal notes untouched.
 if(all[newId] && all[newId].memo==='9/20 15:00訪問'){
  all[newId].memo='9/20 14:30訪問';changed=true;
 }
 if(changed)localStorage.setItem(key,JSON.stringify(all));
}catch(e){console.warn('Doughnut review migration skipped:',e)}
})();
